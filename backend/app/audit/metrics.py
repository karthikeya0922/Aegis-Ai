"""Aggregation over request_audit for the dashboard.

Everything here is a sum, a count or a percentile over rows that were
written by real requests. Nothing is invented: a window with no rows
reports zeros and null percentiles, not placeholders. Every estimated
figure (cost, energy, CO2) carries the `basis` string from its config.

Percentiles are computed in Python over the window's values. SQLite has no
percentile function, and at hackathon scale a window is thousands of rows,
not millions; the query is capped so a runaway window cannot exhaust
memory.
"""

from __future__ import annotations

import json
import math
from collections import Counter
from datetime import datetime, timedelta, timezone

from sqlalchemy import func, select

from app.audit.database import session_scope
from app.audit.estimates import get_pricing, get_sustainability
from app.audit.models import RequestAudit, ReviewRequest
from app.contracts.audit import AuditReport, AuditReportSection
from app.contracts.metrics import (
    CostStats,
    LatencyStats,
    MetricsResponse,
    ProviderMetricsResponse,
    ProviderStat,
    RuleCount,
    SecurityMetricsResponse,
    SustainabilityMetricsResponse,
    TokenStats,
)

_MAX_ROWS = 50_000

DISCLAIMER = (
    "This report is transaction evidence generated by Aegis. It supports a "
    "deployer's own record-keeping and oversight processes. It is not a "
    "conformity assessment and does not itself establish legal compliance. "
    "Cost, energy and carbon figures are estimates whose assumptions are stated "
    "in config/pricing.yaml and config/sustainability.yaml."
)


def _since(window_hours: int) -> datetime:
    return datetime.now(timezone.utc) - timedelta(hours=window_hours)


def _rows(tenant_id: str, window_hours: int) -> list[RequestAudit]:
    with session_scope() as s:
        rows = s.execute(
            select(RequestAudit)
            .where(RequestAudit.tenant_id == tenant_id, RequestAudit.timestamp >= _since(window_hours))
            .order_by(RequestAudit.timestamp.desc())
            .limit(_MAX_ROWS)
        ).scalars().all()
        s.expunge_all()
        return list(rows)


def percentile(values: list[float], p: float) -> float | None:
    """Nearest-rank percentile. None when there is nothing to rank."""
    if not values:
        return None
    ordered = sorted(values)
    rank = math.ceil(p / 100.0 * len(ordered))  # 1-based nearest rank
    k = max(0, min(len(ordered) - 1, rank - 1))
    return round(ordered[k], 3)


def _mean(values: list[float]) -> float | None:
    return round(sum(values) / len(values), 3) if values else None


