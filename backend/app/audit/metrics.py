def overview(tenant_id: str = "default", window_hours: int = 24) -> MetricsResponse:
    rows = _rows(tenant_id, window_hours)
    pricing = get_pricing()

    total = [r.latency_total_ms for r in rows if r.latency_total_ms is not None]
    inspect = [r.latency_inspect_ms for r in rows if r.latency_inspect_ms is not None]

    spend = sum(r.estimated_cost_usd or 0.0 for r in rows)
    saved = sum(r.estimated_savings_usd or 0.0 for r in rows)

    return MetricsResponse(
        window_hours=window_hours,
        total_requests=len(rows),
        blocked_requests=sum(1 for r in rows if r.policy_action == "BLOCK"),
        sanitized_requests=sum(1 for r in rows if r.policy_action == "SANITIZE"),
        latency=LatencyStats(
            p50_ms=percentile(total, 50),
            p95_ms=percentile(total, 95),
            p99_ms=percentile(total, 99),
            mean_ms=_mean(total),
            inspector_overhead_p50_ms=percentile(inspect, 50),
            inspector_overhead_p95_ms=percentile(inspect, 95),
        ),
        tokens=TokenStats(
            input_tokens=sum(r.input_tokens or 0 for r in rows),
            output_tokens=sum(r.output_tokens or 0 for r in rows),
            total_tokens=sum(r.total_tokens or 0 for r in rows),
        ),
        cost=CostStats(
            estimated_spend_usd=round(spend, 6),
            estimated_saved_usd=round(saved, 6),
            basis=(
                f"{pricing.basis} Savings are counted against "
                f"{pricing.savings_counterfactual_model} on cache hits."
            ),
        ),
    )


